  Future<void> loadForLocale(Locale locale) async {
    final tag = locale.toLanguageTag();
    final lang = locale.languageCode;

    if (_loadedTag == tag || _loadingTag == tag) return;
    _loadingTag = tag;

    try {
      final fullDoc = await FirebaseFirestore.instance
          .collection('app_translations')
          .doc(tag)
          .get();
      Map<String, String> values = _extractValues(fullDoc.data());

      if (values.isEmpty) {
        final langDoc = await FirebaseFirestore.instance
            .collection('app_translations')
            .doc(lang)
            .get();
        values = _extractValues(langDoc.data());
      }

      _remoteValues = values;
      _loadedTag = tag;
      revisionNotifier.value = revisionNotifier.value + 1;
    } catch (_) {
      _remoteValues = const {};
      _loadedTag = tag;
      revisionNotifier.value = revisionNotifier.value + 1;
    } finally {
      _loadingTag = '';
    }
  }

  String tr(String key, Locale locale) {
    final remote = _remoteValues[key];
    if (remote != null && remote.isNotEmpty) return remote;

    final fallbackLang = fallbackValues[locale.languageCode];
    if (fallbackLang != null && fallbackLang.containsKey(key)) {
      return fallbackLang[key]!;
    }

    return fallbackValues['en']?[key] ?? key;
  }

  Map<String, String> _extractValues(Map<String, dynamic>? data) {
    if (data == null || data.isEmpty) return const {};

    final valuesNode = data['values'];
    if (valuesNode is Map<String, dynamic>) {
      return valuesNode.map(
        (key, value) => MapEntry(key, value?.toString() ?? ''),
      );
    }

    final extracted = <String, String>{};
    for (final entry in data.entries) {
      if (entry.value is String) {
        extracted[entry.key] = entry.value as String;
      }
    }
    return extracted;
  }
}
